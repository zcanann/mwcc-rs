use crate::{compile, SourceLanguage};

#[test]
fn schedules_coveredge_display_list_packets_byte_exactly() {
    let source = br#"
        typedef unsigned short u16;
        typedef struct Gfx {
            unsigned word0;
            unsigned word1;
        } Gfx;

        extern void gDPSetOtherMode(Gfx*, unsigned, unsigned);

        void coveredge(Gfx** gfxp, u16 ulx, u16 uly, u16 lrx, u16 lry) {
            Gfx* gfx = *gfxp;
            Gfx* first;
            Gfx* second;
            Gfx* third;
            Gfx* fourth;
            Gfx* fifth;

            first = (Gfx*)gfx++;
            first->word0 = 0xe7000000u;
            first->word1 = 0;

            second = (Gfx*)gfx++;
            second->word0 = 0xf9000000u;
            second->word1 = 0xffffff08u;

            third = (Gfx*)gfx++;
            third->word0 = 0xee000000u;
            third->word1 = 0xffffffffu;

            gDPSetOtherMode(gfx++, 3312, 262488132);

            fourth = (Gfx*)gfx++;
            fourth->word0 =
                (((unsigned)246 & 255) << 24)
                | (((unsigned)lrx & 1023) << 14)
                | (((unsigned)lry & 1023) << 2);
            fourth->word1 =
                (((unsigned)ulx & 1023) << 14)
                | (((unsigned)uly & 1023) << 2);

            fifth = (Gfx*)gfx++;
            fifth->word0 = 0xe7000000u;
            fifth->word1 = 0;
            *gfxp = gfx;
        }
    "#;
    let mut flags = mwcc_versions::Flags::default();
    flags.debug_info = false;
    flags.emit_mwcats = false;
    flags.inline_enabled = false;
    let object = compile(
        source,
        "display-list-coveredge.c",
        mwcc_versions::CompilerConfig {
            build: mwcc_versions::GC_2_6,
            flags,
        },
        Some(SourceLanguage::C),
        None,
        false,
    )
    .expect("the coveredge packet sequence should compile");

    // Exact GC/2.6 output measured from Animal Crossing's
    // PreRender_ShowCoveredge.
    let expected = [
        0x94, 0x21, 0xff, 0xf0, 0x54, 0xa0, 0x15, 0x3a, 0x3d, 0x20, 0xef, 0x00, 0x3d, 0x00, 0x0f,
        0xa5, 0x93, 0xe1, 0x00, 0x0c, 0x54, 0xc6, 0x72, 0x22, 0x3f, 0xe0, 0xe7, 0x00, 0x39, 0x80,
        0x00, 0x00, 0x93, 0xc1, 0x00, 0x08, 0x3d, 0x40, 0xf9, 0x00, 0x38, 0xa0, 0xff, 0x08, 0x3d,
        0x60, 0xee, 0x00, 0x83, 0xc3, 0x00, 0x00, 0x39, 0x29, 0x0c, 0xf0, 0x39, 0x08, 0x40, 0x44,
        0x64, 0xc6, 0xf6, 0x00, 0x93, 0xfe, 0x00, 0x00, 0x50, 0x80, 0x72, 0x22, 0x91, 0x9e, 0x00,
        0x04, 0x91, 0x5e, 0x00, 0x08, 0x39, 0x40, 0xff, 0xff, 0x90, 0xbe, 0x00, 0x0c, 0x54, 0xe5,
        0x15, 0x3a, 0x7c, 0xc5, 0x2b, 0x78, 0x91, 0x7e, 0x00, 0x10, 0x91, 0x5e, 0x00, 0x14, 0x91,
        0x3e, 0x00, 0x18, 0x91, 0x1e, 0x00, 0x1c, 0x90, 0xbe, 0x00, 0x20, 0x90, 0x1e, 0x00, 0x24,
        0x3b, 0xde, 0x00, 0x28, 0x7f, 0xc4, 0xf3, 0x78, 0x93, 0xfe, 0x00, 0x00, 0x3b, 0xde, 0x00,
        0x08, 0x91, 0x84, 0x00, 0x04, 0x93, 0xc3, 0x00, 0x00, 0x83, 0xe1, 0x00, 0x0c, 0x83, 0xc1,
        0x00, 0x08, 0x38, 0x21, 0x00, 0x10, 0x4e, 0x80, 0x00, 0x20,
    ];
    assert!(object
        .windows(expected.len())
        .any(|bytes| bytes == expected));
}
