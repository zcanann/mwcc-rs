use crate::{compile, SourceLanguage};

#[test]
fn releases_fixed_intrusive_lists_into_a_global_manager() {
    let source = br#"
        struct Object;
        struct Manager {
            unsigned int count;
            unsigned int reserved;
            struct Object* first;
            struct Object* second;
            struct Object* third;
            struct Object* waiting;
            int tail[23];
        };
        struct Object {
            struct Object* next;
            struct Manager* manager;
            int tail[78];
        };
        extern struct Object* take_object(struct Object** list);
        extern void append_object(struct Object** list, struct Object* object);
        extern void cancel_wait(struct Object* object);

        static struct Manager global_manager;

        int release_all(struct Manager* source) {
            struct Object* object;
            while (1) {
                object = take_object(&source->first);
                if (object == 0) break;
                append_object(&global_manager.first, object);
                object->manager = &global_manager;
            }
            while (1) {
                object = take_object(&source->second);
                if (object == 0) break;
                append_object(&global_manager.second, object);
                object->manager = &global_manager;
            }
            while (1) {
                object = take_object(&source->third);
                if (object == 0) break;
                append_object(&global_manager.third, object);
                object->manager = &global_manager;
            }
            while (1) {
                object = take_object(&source->waiting);
                if (object == 0) break;
                cancel_wait(object);
                append_object(&global_manager.first, object);
                object->manager = &global_manager;
            }
            global_manager.count += source->count;
            source->count = 0;
            return 0;
        }
    "#;
    let mut flags = mwcc_versions::Flags::default();
    flags.debug_info = false;
    flags.cpp_exceptions = false;
    flags.emit_mwcats = false;
    flags.inline_enabled = false;
    flags.use_lmw_stmw = true;
    let object = compile(
        source,
        "release-list-bank-to-global.c",
        mwcc_versions::CompilerConfig {
            build: mwcc_versions::GC_1_2_5,
            flags,
        },
        Some(SourceLanguage::C),
        None,
        false,
    )
    .expect("the global list-bank release should compile");

    let expected = [
        0x7c, 0x08, 0x02, 0xa6, 0x3c, 0x80, 0x00, 0x00, 0x90, 0x01, 0x00, 0x04,
        0x94, 0x21, 0xff, 0xd8, 0xbf, 0x61, 0x00, 0x14, 0x3b, 0xc4, 0x00, 0x00,
        0x3b, 0xe3, 0x00, 0x00, 0x3b, 0x9e, 0x00, 0x08, 0x38, 0x7f, 0x00, 0x08,
        0x48, 0x00, 0x00, 0x01, 0x7c, 0x7b, 0x1b, 0x79, 0x41, 0x82, 0x00, 0x18,
        0x38, 0x7c, 0x00, 0x00, 0x38, 0x9b, 0x00, 0x00, 0x48, 0x00, 0x00, 0x01,
        0x93, 0xdb, 0x00, 0x04, 0x4b, 0xff, 0xff, 0xe0, 0x3b, 0xbe, 0x00, 0x0c,
        0x38, 0x7f, 0x00, 0x0c, 0x48, 0x00, 0x00, 0x01, 0x7c, 0x7b, 0x1b, 0x79,
        0x41, 0x82, 0x00, 0x18, 0x38, 0x7d, 0x00, 0x00, 0x38, 0x9b, 0x00, 0x00,
        0x48, 0x00, 0x00, 0x01, 0x93, 0xdb, 0x00, 0x04, 0x4b, 0xff, 0xff, 0xe0,
        0x3b, 0xbe, 0x00, 0x10, 0x38, 0x7f, 0x00, 0x10, 0x48, 0x00, 0x00, 0x01,
        0x7c, 0x7b, 0x1b, 0x79, 0x41, 0x82, 0x00, 0x18, 0x38, 0x7d, 0x00, 0x00,
        0x38, 0x9b, 0x00, 0x00, 0x48, 0x00, 0x00, 0x01, 0x93, 0xdb, 0x00, 0x04,
        0x4b, 0xff, 0xff, 0xe0, 0x38, 0x7f, 0x00, 0x14, 0x48, 0x00, 0x00, 0x01,
        0x7c, 0x7d, 0x1b, 0x79, 0x41, 0x82, 0x00, 0x20, 0x7f, 0xa3, 0xeb, 0x78,
        0x48, 0x00, 0x00, 0x01, 0x38, 0x7c, 0x00, 0x00, 0x38, 0x9d, 0x00, 0x00,
        0x48, 0x00, 0x00, 0x01, 0x93, 0xdd, 0x00, 0x04, 0x4b, 0xff, 0xff, 0xd8,
        0x80, 0xbe, 0x00, 0x00, 0x38, 0x00, 0x00, 0x00, 0x80, 0x9f, 0x00, 0x00,
        0x38, 0x60, 0x00, 0x00, 0x7c, 0x85, 0x22, 0x14, 0x90, 0x9e, 0x00, 0x00,
        0x90, 0x1f, 0x00, 0x00, 0x80, 0x01, 0x00, 0x2c, 0xbb, 0x61, 0x00, 0x14,
        0x38, 0x21, 0x00, 0x28, 0x7c, 0x08, 0x03, 0xa6, 0x4e, 0x80, 0x00, 0x20,
    ];
    assert!(
        object.windows(expected.len()).any(|bytes| bytes == expected),
        "global list-bank release body was not found in object: {:02x?}",
        object
    );
}
