use crate::{compile, SourceLanguage};

#[test]
fn emits_the_legacy_inlined_payload_event() {
    let source = br#"
        typedef int bool;
        typedef struct Type {
            int unused;
            int size;
            int argument;
            int (*event)(void*, int, void*);
        } Type;
        typedef struct Payload {
            void* list;
            Type* type;
        } Payload;
        typedef struct Registry Registry;

        static Registry* registry;
        extern int test_item(Registry* list, Payload* payload);

        static inline bool find_type(void* object, Type* type) {
            if (object != 0) {
                Payload* payload = *(Payload**)((unsigned char*)object - 4);
                if (test_item(registry, payload)) {
                    if (payload->type == type) {
                        return 1;
                    }
                }
            }
            return 0;
        }

        int dispatch(void* object, int event, void* argument) {
            if (object != 0) {
                Payload* payload = *(Payload**)((unsigned char*)object - 4);
                if (test_item(registry, payload)) {
                    if (find_type(object, payload->type)) {
                        return payload->type->event(object, event, argument);
                    }
                }
            }
            return 0;
        }
    "#;
    let mut flags = mwcc_versions::Flags::default();
    flags.debug_info = false;
    flags.cpp_exceptions = false;
    flags.emit_mwcats = false;
    let object = compile(
        source,
        "inlined-payload-event.c",
        mwcc_versions::CompilerConfig {
            build: mwcc_versions::GC_1_1,
            flags,
        },
        Some(SourceLanguage::C),
        None,
        false,
    )
    .expect("the inlined payload event should compile");

    let expected = [
        0x7c, 0x08, 0x02, 0xa6, 0x90, 0x01, 0x00, 0x04, 0x94, 0x21, 0xff, 0xd0, 0xbf, 0x41, 0x00,
        0x18, 0x7c, 0x7a, 0x1b, 0x79, 0x3b, 0x64, 0x00, 0x00, 0x3b, 0x85, 0x00, 0x00, 0x41, 0x82,
        0x00, 0x84, 0x3b, 0xfa, 0xff, 0xfc, 0x80, 0x60, 0x00, 0x00, 0x83, 0xba, 0xff, 0xfc, 0x7f,
        0xa4, 0xeb, 0x78, 0x48, 0x00, 0x00, 0x01, 0x2c, 0x03, 0x00, 0x00, 0x41, 0x82, 0x00, 0x68,
        0x28, 0x1a, 0x00, 0x00, 0x83, 0xdd, 0x00, 0x04, 0x41, 0x82, 0x00, 0x30, 0x83, 0xff, 0x00,
        0x00, 0x80, 0x60, 0x00, 0x00, 0x7f, 0xe4, 0xfb, 0x78, 0x48, 0x00, 0x00, 0x01, 0x2c, 0x03,
        0x00, 0x00, 0x41, 0x82, 0x00, 0x18, 0x80, 0x1f, 0x00, 0x04, 0x7c, 0x00, 0xf0, 0x40, 0x40,
        0x82, 0x00, 0x0c, 0x38, 0x00, 0x00, 0x01, 0x48, 0x00, 0x00, 0x08, 0x38, 0x00, 0x00, 0x00,
        0x2c, 0x00, 0x00, 0x00, 0x41, 0x82, 0x00, 0x24, 0x80, 0xbd, 0x00, 0x04, 0x38, 0x7a, 0x00,
        0x00, 0x38, 0x9b, 0x00, 0x00, 0x81, 0x85, 0x00, 0x0c, 0x38, 0xbc, 0x00, 0x00, 0x7d, 0x88,
        0x03, 0xa6, 0x4e, 0x80, 0x00, 0x21, 0x48, 0x00, 0x00, 0x08, 0x38, 0x60, 0x00, 0x00, 0xbb,
        0x41, 0x00, 0x18, 0x80, 0x01, 0x00, 0x34, 0x38, 0x21, 0x00, 0x30, 0x7c, 0x08, 0x03, 0xa6,
        0x4e, 0x80, 0x00, 0x20,
    ];
    assert!(object
        .windows(expected.len())
        .any(|bytes| bytes == expected));
}
