use crate::{compile, SourceLanguage};

#[test]
fn compiles_frame_digits_and_the_following_range_test_exactly() {
    let source = br#"
        struct Scene {
            unsigned id;
        };

        struct Globals {
            char padding[8128];
            struct Scene* scene;
        };

        extern struct Globals globals;
        char* idtag(unsigned, int);
        int sprintf(char*, const char*, ...);

        unsigned current_room(void* context) {
            char buffer[16];
            int room;
            unsigned most;
            unsigned char lowercase;

            sprintf(buffer, "%s", idtag(globals.scene->id, 0));
            room = (buffer[2] - '0') * 10 + (buffer[3] - '0');
            most = buffer[0];
            lowercase = 0;
            if (most >= 'a' && most <= 'z')
                lowercase = 1;
            if (lowercase)
                most -= 0x20;
            return room + ((most - 'A') + 1) * 100;
        }
    "#;
    let mut flags = mwcc_versions::Flags::default();
    flags.debug_info = false;
    flags.cpp_exceptions = false;
    flags.emit_mwcats = false;
    flags.string_literals_read_only = true;
    flags.string_literals_packed = true;
    flags.char_default = mwcc_versions::CharDefault::Unsigned;
    let object = compile(
        source,
        "frame-digit-pair.c",
        mwcc_versions::CompilerConfig {
            build: mwcc_versions::GC_2_0P1,
            flags,
        },
        Some(SourceLanguage::C),
        None,
        false,
    )
    .expect("the frame digit pair and following byte range test should compile");

    let expected = [
        0x94, 0x21, 0xff, 0xe0, 0x7c, 0x08, 0x02, 0xa6, 0x3c, 0x60, 0x00, 0x00, 0x38, 0x80, 0x00,
        0x00, 0x90, 0x01, 0x00, 0x24, 0x38, 0x63, 0x00, 0x00, 0x80, 0x63, 0x1f, 0xc0, 0x80, 0x63,
        0x00, 0x00, 0x48, 0x00, 0x00, 0x01, 0x3c, 0x80, 0x00, 0x00, 0x7c, 0x65, 0x1b, 0x78, 0x38,
        0x84, 0x00, 0x00, 0x38, 0x61, 0x00, 0x08, 0x4c, 0xc6, 0x31, 0x82, 0x48, 0x00, 0x00, 0x01,
        0x88, 0x61, 0x00, 0x0a, 0x38, 0x00, 0x00, 0x00, 0x88, 0xa1, 0x00, 0x08, 0x38, 0x63, 0xff,
        0xd0, 0x88, 0x81, 0x00, 0x0b, 0x1c, 0x63, 0x00, 0x0a, 0x28, 0x05, 0x00, 0x61, 0x7c, 0x64,
        0x1a, 0x14, 0x38, 0x63, 0xff, 0xd0, 0x41, 0x80, 0x00, 0x10, 0x28, 0x05, 0x00, 0x7a, 0x41,
        0x81, 0x00, 0x08, 0x38, 0x00, 0x00, 0x01, 0x54, 0x00, 0x06, 0x3f, 0x41, 0x82, 0x00, 0x08,
        0x38, 0xa5, 0xff, 0xe0, 0x38, 0x05, 0xff, 0xc0, 0x1c, 0x00, 0x00, 0x64, 0x7c, 0x63, 0x02,
        0x14, 0x80, 0x01, 0x00, 0x24, 0x7c, 0x08, 0x03, 0xa6, 0x38, 0x21, 0x00, 0x20, 0x4e, 0x80,
        0x00, 0x20,
    ];
    assert!(object
        .windows(expected.len())
        .any(|bytes| bytes == expected));
}
