use crate::{compile, SourceLanguage};

#[test]
fn threads_a_nested_return_through_a_forwarding_block() {
    let source = br#"
        int is_empty(void*, int);

        unsigned probe(void* context) {
            if (is_empty(0, 0) == 1) {
                if (is_empty(0, 1) == 1)
                    return 0;
                if (is_empty(0, 1) == 0)
                    return 2;
            } else {
                if (is_empty(0, 0) == 0) {
                    if (is_empty(0, 1) == 1)
                        return 1;
                    if (is_empty(0, 1) == 0)
                        return 3;
                }
            }
            return 0;
        }
    "#;
    let mut flags = mwcc_versions::Flags::default();
    flags.debug_info = false;
    flags.cpp_exceptions = false;
    flags.emit_mwcats = false;
    let object = compile(
        source,
        "forwarding-branch-cleanup.c",
        mwcc_versions::CompilerConfig {
            build: mwcc_versions::GC_2_0P1,
            flags,
        },
        Some(SourceLanguage::C),
        None,
        false,
    )
    .expect("the nested return control flow should compile");

    // GC/2.0p1 oracle .text. In particular, the bne at +0x4c targets the
    // fallback at +0xa4 directly; there is no branch-only forwarding block.
    let expected = [
        0x94, 0x21, 0xff, 0xf0, 0x7c, 0x08, 0x02, 0xa6, 0x38, 0x60, 0x00, 0x00, 0x38, 0x80, 0x00,
        0x00, 0x90, 0x01, 0x00, 0x14, 0x48, 0x00, 0x00, 0x01, 0x2c, 0x03, 0x00, 0x01, 0x40, 0x82,
        0x00, 0x3c, 0x38, 0x60, 0x00, 0x00, 0x38, 0x80, 0x00, 0x01, 0x48, 0x00, 0x00, 0x01, 0x2c,
        0x03, 0x00, 0x01, 0x40, 0x82, 0x00, 0x0c, 0x38, 0x60, 0x00, 0x00, 0x48, 0x00, 0x00, 0x70,
        0x38, 0x60, 0x00, 0x00, 0x38, 0x80, 0x00, 0x01, 0x48, 0x00, 0x00, 0x01, 0x2c, 0x03, 0x00,
        0x00, 0x40, 0x82, 0x00, 0x58, 0x38, 0x60, 0x00, 0x02, 0x48, 0x00, 0x00, 0x54, 0x38, 0x60,
        0x00, 0x00, 0x38, 0x80, 0x00, 0x00, 0x48, 0x00, 0x00, 0x01, 0x2c, 0x03, 0x00, 0x00, 0x40,
        0x82, 0x00, 0x3c, 0x38, 0x60, 0x00, 0x00, 0x38, 0x80, 0x00, 0x01, 0x48, 0x00, 0x00, 0x01,
        0x2c, 0x03, 0x00, 0x01, 0x40, 0x82, 0x00, 0x0c, 0x38, 0x60, 0x00, 0x01, 0x48, 0x00, 0x00,
        0x24, 0x38, 0x60, 0x00, 0x00, 0x38, 0x80, 0x00, 0x01, 0x48, 0x00, 0x00, 0x01, 0x2c, 0x03,
        0x00, 0x00, 0x40, 0x82, 0x00, 0x0c, 0x38, 0x60, 0x00, 0x03, 0x48, 0x00, 0x00, 0x08, 0x38,
        0x60, 0x00, 0x00, 0x80, 0x01, 0x00, 0x14, 0x7c, 0x08, 0x03, 0xa6, 0x38, 0x21, 0x00, 0x10,
        0x4e, 0x80, 0x00, 0x20,
    ];
    assert!(object
        .windows(expected.len())
        .any(|bytes| bytes == expected));
}
