use crate::{compile, SourceLanguage};

#[test]
fn lowers_call_result_switch_arms_to_a_shared_continuation() {
    let source = br#"
        int pick(void);
        char* copy(char*, const char*);

        char* render(void) {
            static char buffer[32];
            switch (pick()) {
            case 0:
                copy(buffer, "A");
                break;
            case 1:
                copy(buffer, "B");
                break;
            default:
                copy(buffer, "");
                break;
            }
            return buffer;
        }
    "#;
    let mut flags = mwcc_versions::Flags::default();
    flags.debug_info = false;
    flags.cpp_exceptions = false;
    flags.emit_mwcats = false;
    let object = compile(
        source,
        "joined-call-switch.c",
        mwcc_versions::CompilerConfig {
            build: mwcc_versions::GC_2_0P1,
            flags,
        },
        Some(SourceLanguage::C),
        None,
        false,
    )
    .expect("call-bearing switch arms should share the trailing return");

    // Exact GC/2.0p1 schedule: call-result comparison tree; source-order case
    // bodies; branches from both cases to one LR-reload/address-return block.
    let entry = [
        0x94, 0x21, 0xff, 0xf0, 0x7c, 0x08, 0x02, 0xa6, 0x90, 0x01, 0x00, 0x14, 0x48, 0x00, 0x00,
        0x01, 0x2c, 0x03, 0x00, 0x01, 0x41, 0x82, 0x00, 0x28, 0x40, 0x80, 0x00, 0x38, 0x2c, 0x03,
        0x00, 0x00, 0x40, 0x80, 0x00, 0x08, 0x48, 0x00, 0x00, 0x2c, 0x3c, 0x60, 0x00, 0x00, 0x38,
        0x80, 0x00, 0x00, 0x38, 0x63, 0x00, 0x00, 0x48, 0x00, 0x00, 0x01, 0x48, 0x00, 0x00, 0x28,
        0x3c, 0x60, 0x00, 0x00, 0x38, 0x80, 0x00, 0x00, 0x38, 0x63, 0x00, 0x00, 0x48, 0x00, 0x00,
        0x01, 0x48, 0x00, 0x00, 0x14, 0x3c, 0x60, 0x00, 0x00, 0x38, 0x80, 0x00, 0x00, 0x38, 0x63,
        0x00, 0x00, 0x48, 0x00, 0x00, 0x01, 0x80, 0x01, 0x00, 0x14, 0x3c, 0x60, 0x00, 0x00, 0x38,
        0x63, 0x00, 0x00, 0x7c, 0x08, 0x03, 0xa6, 0x38, 0x21, 0x00, 0x10, 0x4e, 0x80, 0x00, 0x20,
    ];
    assert!(object.windows(entry.len()).any(|bytes| bytes == entry));
}
