use crate::{compile, SourceLanguage};

#[test]
fn emits_the_legacy_payload_object_free() {
    let source = br#"
        typedef struct Type {
            int unused;
            int size;
            int argument;
            int (*event)(void*, int, void*);
        } Type;
        typedef struct Payload {
            void* list;
            Type* type;
        } Payload;

        extern int free_item(void* list, void** output);

        int release(void** output) {
            if (output != 0 && *output != 0) {
                Payload* payload = *(Payload**)((unsigned char*)*output - 4);
                payload->type->event(*output, 3, 0);
                *output = (unsigned char*)*output - 4;
                if (free_item(payload->list, output) == 0) {
                    return 0;
                }
                *output = 0;
                return 1;
            }
            return 0;
        }
    "#;
    let mut flags = mwcc_versions::Flags::default();
    flags.debug_info = false;
    flags.cpp_exceptions = false;
    flags.emit_mwcats = false;
    let object = compile(
        source,
        "payload-object-free.c",
        mwcc_versions::CompilerConfig {
            build: mwcc_versions::GC_1_1,
            flags,
        },
        Some(SourceLanguage::C),
        None,
        false,
    )
    .expect("the payload object free should compile");

    let expected = [
        0x7c, 0x08, 0x02, 0xa6, 0x90, 0x01, 0x00, 0x04, 0x94, 0x21, 0xff, 0xe8, 0x93, 0xe1, 0x00,
        0x14, 0x93, 0xc1, 0x00, 0x10, 0x7c, 0x7e, 0x1b, 0x79, 0x41, 0x82, 0x00, 0x64, 0x80, 0x7e,
        0x00, 0x00, 0x28, 0x03, 0x00, 0x00, 0x41, 0x82, 0x00, 0x58, 0x83, 0xe3, 0xff, 0xfc, 0x38,
        0x80, 0x00, 0x03, 0x38, 0xa0, 0x00, 0x00, 0x80, 0xdf, 0x00, 0x04, 0x81, 0x86, 0x00, 0x0c,
        0x7d, 0x88, 0x03, 0xa6, 0x4e, 0x80, 0x00, 0x21, 0x80, 0x7e, 0x00, 0x00, 0x38, 0x9e, 0x00,
        0x00, 0x38, 0x03, 0xff, 0xfc, 0x90, 0x1e, 0x00, 0x00, 0x80, 0x7f, 0x00, 0x00, 0x48, 0x00,
        0x00, 0x01, 0x2c, 0x03, 0x00, 0x00, 0x40, 0x82, 0x00, 0x0c, 0x38, 0x60, 0x00, 0x00, 0x48,
        0x00, 0x00, 0x18, 0x38, 0x00, 0x00, 0x00, 0x90, 0x1e, 0x00, 0x00, 0x38, 0x60, 0x00, 0x01,
        0x48, 0x00, 0x00, 0x08, 0x38, 0x60, 0x00, 0x00, 0x80, 0x01, 0x00, 0x1c, 0x83, 0xe1, 0x00,
        0x14, 0x83, 0xc1, 0x00, 0x10, 0x7c, 0x08, 0x03, 0xa6, 0x38, 0x21, 0x00, 0x18, 0x4e, 0x80,
        0x00, 0x20,
    ];
    assert!(object
        .windows(expected.len())
        .any(|bytes| bytes == expected));
}
