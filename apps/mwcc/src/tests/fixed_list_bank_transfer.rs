use crate::{compile, SourceLanguage};

#[test]
fn transfers_four_intrusive_lists_and_their_adjacent_counters() {
    let source = br#"
        struct Object;
        struct Manager {
            unsigned int count;
            unsigned int secondary_count;
            struct Object* first;
            struct Object* second;
            struct Object* third;
            struct Object* fourth;
            int tail[23];
        };
        struct Object {
            struct Object* next;
            struct Manager* manager;
            int tail[78];
        };
        extern struct Object* take_object(struct Object** list);
        extern void append_object(struct Object** list, struct Object* object);

        int transfer_all(struct Manager* source, struct Manager* destination) {
            struct Object* object;
            int padding[2];
            while (1) {
                object = take_object(&source->first);
                if (object == 0) break;
                append_object(&destination->first, object);
                object->manager = destination;
            }
            while (1) {
                object = take_object(&source->second);
                if (object == 0) break;
                append_object(&destination->second, object);
                object->manager = destination;
            }
            while (1) {
                object = take_object(&source->third);
                if (object == 0) break;
                append_object(&destination->third, object);
                object->manager = destination;
            }
            while (1) {
                object = take_object(&source->fourth);
                if (object == 0) break;
                append_object(&destination->fourth, object);
                object->manager = destination;
            }
            destination->count += source->count;
            source->count = 0;
            destination->secondary_count += source->secondary_count;
            source->secondary_count = 0;
            return 0;
            do {
            } while (0);
        }
    "#;
    let mut flags = mwcc_versions::Flags::default();
    flags.debug_info = false;
    flags.cpp_exceptions = false;
    flags.emit_mwcats = false;
    flags.inline_enabled = false;
    flags.use_lmw_stmw = true;
    let object = compile(
        source,
        "fixed-list-bank-transfer.c",
        mwcc_versions::CompilerConfig {
            build: mwcc_versions::GC_1_2_5,
            flags,
        },
        Some(SourceLanguage::C),
        None,
        false,
    )
    .expect("the fixed list-bank transfer should compile");

    let expected = [
        0x7c, 0x08, 0x02, 0xa6, 0x90, 0x01, 0x00, 0x04, 0x94, 0x21, 0xff, 0xd8,
        0xbf, 0xa1, 0x00, 0x1c, 0x3b, 0xa3, 0x00, 0x00, 0x3b, 0xc4, 0x00, 0x00,
        0x38, 0x7d, 0x00, 0x08, 0x48, 0x00, 0x00, 0x01, 0x7c, 0x7f, 0x1b, 0x79,
        0x41, 0x82, 0x00, 0x18, 0x38, 0x7e, 0x00, 0x08, 0x38, 0x9f, 0x00, 0x00,
        0x48, 0x00, 0x00, 0x01, 0x93, 0xdf, 0x00, 0x04, 0x4b, 0xff, 0xff, 0xe0,
        0x38, 0x7d, 0x00, 0x0c, 0x48, 0x00, 0x00, 0x01, 0x7c, 0x7f, 0x1b, 0x79,
        0x41, 0x82, 0x00, 0x18, 0x38, 0x7e, 0x00, 0x0c, 0x38, 0x9f, 0x00, 0x00,
        0x48, 0x00, 0x00, 0x01, 0x93, 0xdf, 0x00, 0x04, 0x4b, 0xff, 0xff, 0xe0,
        0x38, 0x7d, 0x00, 0x10, 0x48, 0x00, 0x00, 0x01, 0x7c, 0x7f, 0x1b, 0x79,
        0x41, 0x82, 0x00, 0x18, 0x38, 0x7e, 0x00, 0x10, 0x38, 0x9f, 0x00, 0x00,
        0x48, 0x00, 0x00, 0x01, 0x93, 0xdf, 0x00, 0x04, 0x4b, 0xff, 0xff, 0xe0,
        0x38, 0x7d, 0x00, 0x14, 0x48, 0x00, 0x00, 0x01, 0x7c, 0x7f, 0x1b, 0x79,
        0x41, 0x82, 0x00, 0x18, 0x38, 0x7e, 0x00, 0x14, 0x38, 0x9f, 0x00, 0x00,
        0x48, 0x00, 0x00, 0x01, 0x93, 0xdf, 0x00, 0x04, 0x4b, 0xff, 0xff, 0xe0,
        0x80, 0x9e, 0x00, 0x00, 0x38, 0xa0, 0x00, 0x00, 0x80, 0x1d, 0x00, 0x00,
        0x38, 0x60, 0x00, 0x00, 0x7c, 0x04, 0x02, 0x14, 0x90, 0x1e, 0x00, 0x00,
        0x90, 0xbd, 0x00, 0x00, 0x80, 0x9e, 0x00, 0x04, 0x80, 0x1d, 0x00, 0x04,
        0x7c, 0x04, 0x02, 0x14, 0x90, 0x1e, 0x00, 0x04, 0x90, 0xbd, 0x00, 0x04,
        0x80, 0x01, 0x00, 0x2c, 0xbb, 0xa1, 0x00, 0x1c, 0x38, 0x21, 0x00, 0x28,
        0x7c, 0x08, 0x03, 0xa6, 0x4e, 0x80, 0x00, 0x20,
    ];
    assert!(
        object.windows(expected.len()).any(|bytes| bytes == expected),
        "fixed list-bank transfer body was not found in object: {:02x?}",
        object
    );
}
