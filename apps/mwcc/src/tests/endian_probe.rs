use crate::{compile, SourceLanguage};

#[test]
fn schedules_a_runtime_endian_probe_as_one_region() {
    let source = br#"
        extern int endian;

        int detect(void) {
            unsigned char bytes[4];
            int result = 0;
            endian = 1;
            bytes[0] = 0x12;
            bytes[1] = 0x34;
            bytes[2] = 0x56;
            bytes[3] = 0x78;
            if (*(unsigned int*)bytes == 0x12345678) {
                endian = 1;
            } else if (*(unsigned int*)bytes == 0x78563412) {
                endian = 0;
            } else {
                result = 1;
            }
            return result;
        }
    "#;
    let mut flags = mwcc_versions::Flags::default();
    flags.debug_info = false;
    flags.cpp_exceptions = false;
    flags.emit_mwcats = false;
    flags.inline_enabled = false;
    flags.global_addressing = mwcc_versions::GlobalAddressing::Absolute;
    let object = compile(
        source,
        "endian-probe.c",
        mwcc_versions::CompilerConfig {
            build: mwcc_versions::GC_1_2_5N,
            flags,
        },
        Some(SourceLanguage::C),
        None,
        false,
    )
    .expect("the runtime endian probe should compile");

    let expected = [
        0x3c, 0x60, 0x00, 0x00, 0x94, 0x21, 0xff, 0xf0, 0x38, 0xa3, 0x00, 0x00, 0x38, 0xc0,
        0x00, 0x01, 0x90, 0xc5, 0x00, 0x00, 0x38, 0x00, 0x00, 0x12, 0x38, 0x60, 0x00, 0x34,
        0x98, 0x01, 0x00, 0x08, 0x38, 0x80, 0x00, 0x56, 0x38, 0x00, 0x00, 0x78, 0x98, 0x61,
        0x00, 0x09, 0x38, 0x60, 0x00, 0x00, 0x98, 0x81, 0x00, 0x0a, 0x98, 0x01, 0x00, 0x0b,
        0x80, 0x81, 0x00, 0x08, 0x3c, 0x04, 0xed, 0xcc, 0x28, 0x00, 0x56, 0x78, 0x40, 0x82,
        0x00, 0x0c, 0x90, 0xc5, 0x00, 0x00, 0x48, 0x00, 0x00, 0x20, 0x3c, 0x04, 0x87, 0xaa,
        0x28, 0x00, 0x34, 0x12, 0x40, 0x82, 0x00, 0x10, 0x38, 0x00, 0x00, 0x00, 0x90, 0x05,
        0x00, 0x00, 0x48, 0x00, 0x00, 0x08, 0x38, 0x60, 0x00, 0x01, 0x38, 0x21, 0x00, 0x10,
        0x4e, 0x80, 0x00, 0x20,
    ];
    assert!(object
        .windows(expected.len())
        .any(|bytes| bytes == expected));
}
