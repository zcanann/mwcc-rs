use crate::{compile, SourceLanguage};

fn compile_convert(build: mwcc_versions::CompilerBuild) -> Vec<u8> {
    let source = br#"
        struct Value {
            unsigned short x;
        };

        float convert(struct Value* value) {
            return (float)value->x;
        }
    "#;
    let mut flags = mwcc_versions::Flags::default();
    flags.debug_info = false;
    flags.emit_mwcats = false;
    flags.inline_enabled = false;
    compile(
        source,
        "unsigned-narrow-to-float.c",
        mwcc_versions::CompilerConfig { build, flags },
        Some(SourceLanguage::C),
        None,
        false,
    )
    .expect("an unsigned halfword load should convert to float")
}

#[test]
fn schedules_unsigned_halfword_to_float_across_optimizer_families() {
    // Exact output measured from the corresponding mwcceppc builds.
    let build_163 = [
        0x94, 0x21, 0xff, 0xe8, 0x3c, 0x00, 0x43, 0x30, 0xa0, 0x63, 0x00, 0x00,
        0xc8, 0x20, 0x00, 0x00, 0x90, 0x61, 0x00, 0x14, 0x90, 0x01, 0x00, 0x10,
        0xc8, 0x01, 0x00, 0x10, 0xec, 0x20, 0x08, 0x28, 0x38, 0x21, 0x00, 0x18,
        0x4e, 0x80, 0x00, 0x20,
    ];
    let patch_1 = [
        0x94, 0x21, 0xff, 0xf0, 0x3c, 0x00, 0x43, 0x30, 0xa0, 0x63, 0x00, 0x00,
        0x90, 0x01, 0x00, 0x08, 0xc8, 0x20, 0x00, 0x00, 0x90, 0x61, 0x00, 0x0c,
        0xc8, 0x01, 0x00, 0x08, 0xec, 0x20, 0x08, 0x28, 0x38, 0x21, 0x00, 0x10,
        0x4e, 0x80, 0x00, 0x20,
    ];
    let mainline = [
        0x94, 0x21, 0xff, 0xf0, 0x3c, 0x00, 0x43, 0x30, 0xc8, 0x20, 0x00, 0x00,
        0xa0, 0x63, 0x00, 0x00, 0x90, 0x01, 0x00, 0x08, 0x90, 0x61, 0x00, 0x0c,
        0xc8, 0x01, 0x00, 0x08, 0xec, 0x20, 0x08, 0x28, 0x38, 0x21, 0x00, 0x10,
        0x4e, 0x80, 0x00, 0x20,
    ];

    for (build, expected) in [
        (mwcc_versions::GC_1_2_5N, build_163.as_slice()),
        (mwcc_versions::GC_2_0P1, patch_1.as_slice()),
        (mwcc_versions::GC_2_6, mainline.as_slice()),
    ] {
        let object = compile_convert(build);
        assert!(
            object
                .windows(expected.len())
                .any(|bytes| bytes == expected),
            "{} did not match its loaded conversion schedule",
            build.label
        );
    }
}
