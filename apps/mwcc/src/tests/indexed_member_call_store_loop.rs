use crate::{compile, SourceLanguage};

#[test]
fn walks_struct_members_through_a_call_result_store() {
    let source = br#"
        struct Entry {
            int reserved;
            unsigned id;
            const char* name;
            int padding;
        };
        extern unsigned hash(const char*);

        void initialize(struct Entry* table) {
            int i;
            for (i = 0; i < 18; i++)
                table[i].id = hash(table[i].name);
        }
    "#;
    let mut flags = mwcc_versions::Flags::default();
    flags.debug_info = false;
    flags.cpp_exceptions = false;
    flags.emit_mwcats = false;
    let object = compile(
        source,
        "indexed-member-call-store-loop.c",
        mwcc_versions::CompilerConfig {
            build: mwcc_versions::GC_2_0P1,
            flags,
        },
        Some(SourceLanguage::C),
        None,
        false,
    )
    .expect("the indexed member call/store loop should compile");

    let entry = [
        0x94, 0x21, 0xff, 0xf0, 0x7c, 0x08, 0x02, 0xa6, 0x90, 0x01, 0x00, 0x14, 0x93, 0xe1, 0x00,
        0x0c, 0x7c, 0x7f, 0x1b, 0x78, 0x93, 0xc1, 0x00, 0x08, 0x3b, 0xc0, 0x00, 0x00, 0x80, 0x7f,
        0x00, 0x08, 0x48, 0x00, 0x00, 0x01, 0x3b, 0xde, 0x00, 0x01, 0x90, 0x7f, 0x00, 0x04, 0x2c,
        0x1e, 0x00, 0x12, 0x3b, 0xff, 0x00, 0x10, 0x41, 0x80, 0xff, 0xe8, 0x80, 0x01, 0x00, 0x14,
        0x83, 0xe1, 0x00, 0x0c, 0x83, 0xc1, 0x00, 0x08, 0x7c, 0x08, 0x03, 0xa6, 0x38, 0x21, 0x00,
        0x10, 0x4e, 0x80, 0x00, 0x20,
    ];
    assert!(object.windows(entry.len()).any(|bytes| bytes == entry));
}
