use crate::{compile, SourceLanguage};

#[test]
fn emits_the_legacy_global_list_teardown() {
    let source = br#"
        typedef struct List {
            int count;
            int size;
            void* head;
        } List;

        static List* registry;
        extern int free_list(void* list);

        int reset(void) {
            void* node;
            node = registry->head;
            while (node != 0) {
                if (!free_list((void*)((unsigned char*)node + 4))) {
                    return 0;
                }
                node = *(void**)node;
            }
            if (!free_list(&registry)) {
                return 0;
            }
            return 1;
        }
    "#;
    let mut flags = mwcc_versions::Flags::default();
    flags.debug_info = false;
    flags.cpp_exceptions = false;
    flags.emit_mwcats = false;
    let object = compile(
        source,
        "global-list-teardown.c",
        mwcc_versions::CompilerConfig {
            build: mwcc_versions::GC_1_1,
            flags,
        },
        Some(SourceLanguage::C),
        None,
        false,
    )
    .expect("the global list teardown should compile");

    let expected = [
        0x7c, 0x08, 0x02, 0xa6, 0x90, 0x01, 0x00, 0x04, 0x94, 0x21, 0xff, 0xf0, 0x93, 0xe1, 0x00,
        0x0c, 0x80, 0x60, 0x00, 0x00, 0x83, 0xe3, 0x00, 0x08, 0x48, 0x00, 0x00, 0x20, 0x38, 0x7f,
        0x00, 0x04, 0x48, 0x00, 0x00, 0x01, 0x2c, 0x03, 0x00, 0x00, 0x40, 0x82, 0x00, 0x0c, 0x38,
        0x60, 0x00, 0x00, 0x48, 0x00, 0x00, 0x2c, 0x83, 0xff, 0x00, 0x00, 0x28, 0x1f, 0x00, 0x00,
        0x40, 0x82, 0xff, 0xe0, 0x38, 0x60, 0x00, 0x00, 0x48, 0x00, 0x00, 0x01, 0x2c, 0x03, 0x00,
        0x00, 0x40, 0x82, 0x00, 0x0c, 0x38, 0x60, 0x00, 0x00, 0x48, 0x00, 0x00, 0x08, 0x38, 0x60,
        0x00, 0x01, 0x80, 0x01, 0x00, 0x14, 0x83, 0xe1, 0x00, 0x0c, 0x38, 0x21, 0x00, 0x10, 0x7c,
        0x08, 0x03, 0xa6, 0x4e, 0x80, 0x00, 0x20,
    ];
    assert!(object
        .windows(expected.len())
        .any(|bytes| bytes == expected));
}
