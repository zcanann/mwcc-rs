use crate::{compile, SourceLanguage};

#[test]
fn schedules_display_list_framebuffer_packets_byte_exactly() {
    let source = br#"
        typedef struct Gfx {
            unsigned word0;
            unsigned word1;
        } Gfx;

        Gfx* setup(Gfx* gfx, void* pointer, unsigned width, unsigned height) {
            Gfx* first;
            Gfx* second;
            Gfx* third;
            first = (Gfx*)(gfx + 0);
            first->word0 = 0xe7000000u;
            first->word1 = 0;
            second = (Gfx*)(gfx + 1);
            second->word0 = 0xff100000u | ((width - 1) & 4095);
            second->word1 = (unsigned)pointer;
            third = (Gfx*)(gfx + 2);
            third->word0 =
                0xed000000u
                | (((unsigned)(int)((float)0 * 4.0f) & 4095) << 12)
                | (((unsigned)(int)((float)0 * 4.0f) & 4095) << 0);
            third->word1 =
                (((unsigned)(int)((float)width * 4.0f) & 4095) << 12)
                | (((unsigned)(int)((float)height * 4.0f) & 4095) << 0);
            return gfx + 3;
        }
    "#;
    let mut flags = mwcc_versions::Flags::default();
    flags.debug_info = false;
    flags.emit_mwcats = false;
    flags.inline_enabled = false;
    let object = compile(
        source,
        "display-list-framebuffer-setup.c",
        mwcc_versions::CompilerConfig {
            build: mwcc_versions::GC_2_6,
            flags,
        },
        Some(SourceLanguage::C),
        None,
        false,
    )
    .expect("the framebuffer packet setup should compile");

    // Exact GC/2.6 output measured from Animal Crossing's gfx_SetUpCFB.
    let expected = [
        0x94, 0x21, 0xff, 0xd0, 0x3c, 0x00, 0x43, 0x30, 0x3c, 0xe0, 0x00, 0x00, 0x7c, 0x68, 0x1b,
        0x78, 0x90, 0xc1, 0x00, 0x1c, 0x38, 0xc7, 0x00, 0x00, 0xc8, 0x46, 0x00, 0x00, 0x3c, 0xe0,
        0x00, 0x00, 0x90, 0x01, 0x00, 0x18, 0x38, 0x67, 0x00, 0x00, 0xc0, 0x63, 0x00, 0x00, 0x3c,
        0xe0, 0xe7, 0x00, 0xc8, 0x01, 0x00, 0x18, 0x38, 0xc5, 0xff, 0xff, 0x90, 0xa1, 0x00, 0x0c,
        0x54, 0xc5, 0x05, 0x3e, 0xec, 0x00, 0x10, 0x28, 0x38, 0xc0, 0x00, 0x00, 0x90, 0x01, 0x00,
        0x08, 0x64, 0xa0, 0xff, 0x10, 0x3c, 0xa0, 0xed, 0x00, 0x38, 0x68, 0x00, 0x18, 0xc8, 0x21,
        0x00, 0x08, 0xec, 0x03, 0x00, 0x32, 0x90, 0xe8, 0x00, 0x00, 0xec, 0x21, 0x10, 0x28, 0xfc,
        0x00, 0x00, 0x1e, 0x90, 0xc8, 0x00, 0x04, 0x90, 0x08, 0x00, 0x08, 0xec, 0x23, 0x00, 0x72,
        0xd8, 0x01, 0x00, 0x20, 0xfc, 0x00, 0x08, 0x1e, 0x90, 0x88, 0x00, 0x0c, 0x80, 0x01, 0x00,
        0x24, 0xd8, 0x01, 0x00, 0x10, 0x54, 0x00, 0x05, 0x3e, 0x80, 0x81, 0x00, 0x14, 0x90, 0xa8,
        0x00, 0x10, 0x50, 0x80, 0x62, 0x26, 0x90, 0x08, 0x00, 0x14, 0x38, 0x21, 0x00, 0x30, 0x4e,
        0x80, 0x00, 0x20,
    ];
    assert!(object
        .windows(expected.len())
        .any(|bytes| bytes == expected));
}
