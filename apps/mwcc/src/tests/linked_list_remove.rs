use crate::{compile, SourceLanguage};

#[test]
fn emits_the_legacy_rotated_remove_transaction() {
    let source = br#"
        typedef struct List {
            int item_size;
            int item_count;
            void* head;
            void* next;
        } List;

        extern int release(void** allocation);

        int remove(List* list, void** item_out) {
            void* cursor;
            void* next;

            if (list->head == 0) {
                return 0;
            }
            cursor = &list->head;
            while (cursor != 0) {
                next = *(void**)cursor;
                if (*item_out == (unsigned char*)next + 4) {
                    *(void**)cursor = *(void**)next;
                    *item_out = 0;
                    if (!release(&next)) {
                        return 0;
                    }
                    list->item_count = list->item_count - 1;
                    return 1;
                }
                cursor = next;
            }
            (void)0;
            return 0;
        }
    "#;
    let mut flags = mwcc_versions::Flags::default();
    flags.debug_info = false;
    flags.cpp_exceptions = false;
    flags.emit_mwcats = false;
    let object = compile(
        source,
        "linked-list-remove.c",
        mwcc_versions::CompilerConfig {
            build: mwcc_versions::GC_1_1,
            flags,
        },
        Some(SourceLanguage::C),
        None,
        false,
    )
    .expect("the linked-list removal should compile");

    let expected = [
        0x7c, 0x08, 0x02, 0xa6, 0x90, 0x01, 0x00, 0x04, 0x94, 0x21, 0xff, 0xe0, 0x93, 0xe1, 0x00,
        0x1c, 0x7c, 0x7f, 0x1b, 0x78, 0x80, 0x03, 0x00, 0x08, 0x28, 0x00, 0x00, 0x00, 0x40, 0x82,
        0x00, 0x0c, 0x38, 0x60, 0x00, 0x00, 0x48, 0x00, 0x00, 0x74, 0x38, 0xdf, 0x00, 0x08, 0x48,
        0x00, 0x00, 0x60, 0x80, 0x06, 0x00, 0x00, 0x90, 0x01, 0x00, 0x10, 0x80, 0xa1, 0x00, 0x10,
        0x80, 0x64, 0x00, 0x00, 0x38, 0x05, 0x00, 0x04, 0x7c, 0x03, 0x00, 0x40, 0x40, 0x82, 0x00,
        0x40, 0x80, 0xa5, 0x00, 0x00, 0x38, 0x00, 0x00, 0x00, 0x38, 0x61, 0x00, 0x10, 0x90, 0xa6,
        0x00, 0x00, 0x90, 0x04, 0x00, 0x00, 0x48, 0x00, 0x00, 0x01, 0x2c, 0x03, 0x00, 0x00, 0x40,
        0x82, 0x00, 0x0c, 0x38, 0x60, 0x00, 0x00, 0x48, 0x00, 0x00, 0x28, 0x80, 0x9f, 0x00, 0x04,
        0x38, 0x60, 0x00, 0x01, 0x38, 0x04, 0xff, 0xff, 0x90, 0x1f, 0x00, 0x04, 0x48, 0x00, 0x00,
        0x14, 0x7c, 0xa6, 0x2b, 0x78, 0x28, 0x06, 0x00, 0x00, 0x40, 0x82, 0xff, 0xa0, 0x38, 0x60,
        0x00, 0x00, 0x80, 0x01, 0x00, 0x24, 0x83, 0xe1, 0x00, 0x1c, 0x38, 0x21, 0x00, 0x20, 0x7c,
        0x08, 0x03, 0xa6, 0x4e, 0x80, 0x00, 0x20,
    ];
    assert!(object
        .windows(expected.len())
        .any(|bytes| bytes == expected));
}
