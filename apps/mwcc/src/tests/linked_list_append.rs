use crate::{compile, SourceLanguage};

#[test]
fn emits_the_legacy_rotated_append_transaction() {
    let source = br#"
        typedef struct List {
            int item_size;
            int item_count;
            void* head;
            void* next;
        } List;

        extern int allocate(void** output, int size);

        int append(List* list, void** item_out) {
            int size;
            void* allocated_node;
            void* cursor;
            void* next;

            size = list->item_size + 4;
            if (!allocate(&allocated_node, size)) {
                return 0;
            }
            *(void**)allocated_node = 0;
            *item_out = (unsigned char*)allocated_node + 4;
            cursor = &list->head;
            while (cursor != 0) {
                next = *(void**)cursor;
                if (next == 0) {
                    *(void**)cursor = allocated_node;
                    list->item_count = list->item_count + 1;
                    return 1;
                }
                cursor = next;
            }
            return 0;
        }
    "#;
    let mut flags = mwcc_versions::Flags::default();
    flags.debug_info = false;
    flags.cpp_exceptions = false;
    flags.emit_mwcats = false;
    let object = compile(
        source,
        "linked-list-append.c",
        mwcc_versions::CompilerConfig {
            build: mwcc_versions::GC_1_1,
            flags,
        },
        Some(SourceLanguage::C),
        None,
        false,
    )
    .expect("the linked-list append should compile");

    let expected = [
        0x7c, 0x08, 0x02, 0xa6, 0x90, 0x01, 0x00, 0x04, 0x94, 0x21, 0xff, 0xe0, 0x93, 0xe1,
        0x00, 0x1c, 0x3b, 0xe4, 0x00, 0x00, 0x93, 0xc1, 0x00, 0x18, 0x7c, 0x7e, 0x1b, 0x78,
        0x80, 0xa3, 0x00, 0x00, 0x38, 0x61, 0x00, 0x10, 0x38, 0x85, 0x00, 0x04, 0x48, 0x00,
        0x00, 0x01, 0x2c, 0x03, 0x00, 0x00, 0x40, 0x82, 0x00, 0x0c, 0x38, 0x60, 0x00, 0x00,
        0x48, 0x00, 0x00, 0x5c, 0x80, 0x61, 0x00, 0x10, 0x38, 0x00, 0x00, 0x00, 0x38, 0x9e,
        0x00, 0x08, 0x90, 0x03, 0x00, 0x00, 0x80, 0x61, 0x00, 0x10, 0x38, 0x03, 0x00, 0x04,
        0x90, 0x1f, 0x00, 0x00, 0x48, 0x00, 0x00, 0x30, 0x80, 0x04, 0x00, 0x00, 0x28, 0x00,
        0x00, 0x00, 0x40, 0x82, 0x00, 0x20, 0x80, 0x01, 0x00, 0x10, 0x38, 0x60, 0x00, 0x01,
        0x90, 0x04, 0x00, 0x00, 0x80, 0x9e, 0x00, 0x04, 0x38, 0x04, 0x00, 0x01, 0x90, 0x1e,
        0x00, 0x04, 0x48, 0x00, 0x00, 0x14, 0x7c, 0x04, 0x03, 0x78, 0x28, 0x04, 0x00, 0x00,
        0x40, 0x82, 0xff, 0xd0, 0x38, 0x60, 0x00, 0x00, 0x80, 0x01, 0x00, 0x24, 0x83, 0xe1,
        0x00, 0x1c, 0x83, 0xc1, 0x00, 0x18, 0x7c, 0x08, 0x03, 0xa6, 0x38, 0x21, 0x00, 0x20,
        0x4e, 0x80, 0x00, 0x20,
    ];
    assert!(object.windows(expected.len()).any(|bytes| bytes == expected));
}
