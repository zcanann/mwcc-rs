use crate::{compile, SourceLanguage};

#[test]
fn emits_the_legacy_resource_event_switch() {
    let source = br#"
        typedef struct Info {
            int words[15];
        } Info;
        typedef struct File {
            int unused;
            void* data;
            void* buffer;
            int pad;
            int size;
            int position;
            int kind;
            Info info;
        } File;

        extern int take_heap(void**, unsigned int);
        extern int free_heap(void**);
        extern int close_info(Info*);

        int file_event(File* file, int event, void* argument) {
            switch (event) {
                case 2:
                    file->size = 0;
                    file->position = 0;
                    file->data = 0;
                    if (!take_heap(&file->buffer, 0x30001024)) {
                        return 0;
                    }
                    break;
                case 3:
                    close_info(&file->info);
                    if (!free_heap(&file->buffer)) {
                        return 0;
                    }
                    break;
                case 0:
                case 1:
                case 4:
                    break;
                default:
                    return 0;
            }
            return 1;
        }
    "#;
    let mut flags = mwcc_versions::Flags::default();
    flags.debug_info = false;
    flags.cpp_exceptions = false;
    flags.emit_mwcats = false;
    let object = compile(
        source,
        "resource-event-switch.c",
        mwcc_versions::CompilerConfig {
            build: mwcc_versions::GC_1_1,
            flags,
        },
        Some(SourceLanguage::C),
        None,
        false,
    )
    .expect("the resource event switch should compile");

    let expected = [
        0x7c, 0x08, 0x02, 0xa6, 0x2c, 0x04, 0x00, 0x03, 0x90, 0x01, 0x00, 0x04, 0x94, 0x21, 0xff,
        0xe0, 0x93, 0xe1, 0x00, 0x1c, 0x3b, 0xe3, 0x00, 0x00, 0x41, 0x82, 0x00, 0x58, 0x40, 0x80,
        0x00, 0x18, 0x2c, 0x04, 0x00, 0x02, 0x40, 0x80, 0x00, 0x1c, 0x2c, 0x04, 0x00, 0x00, 0x40,
        0x80, 0x00, 0x6c, 0x48, 0x00, 0x00, 0x60, 0x2c, 0x04, 0x00, 0x05, 0x40, 0x80, 0x00, 0x58,
        0x48, 0x00, 0x00, 0x5c, 0x38, 0x00, 0x00, 0x00, 0x90, 0x1f, 0x00, 0x10, 0x3c, 0x80, 0x30,
        0x00, 0x38, 0x7f, 0x00, 0x08, 0x90, 0x1f, 0x00, 0x14, 0x38, 0x84, 0x10, 0x24, 0x90, 0x1f,
        0x00, 0x04, 0x48, 0x00, 0x00, 0x01, 0x2c, 0x03, 0x00, 0x00, 0x40, 0x82, 0x00, 0x34, 0x38,
        0x60, 0x00, 0x00, 0x48, 0x00, 0x00, 0x30, 0x38, 0x7f, 0x00, 0x1c, 0x48, 0x00, 0x00, 0x01,
        0x38, 0x7f, 0x00, 0x08, 0x48, 0x00, 0x00, 0x01, 0x2c, 0x03, 0x00, 0x00, 0x40, 0x82, 0x00,
        0x14, 0x38, 0x60, 0x00, 0x00, 0x48, 0x00, 0x00, 0x10, 0x38, 0x60, 0x00, 0x00, 0x48, 0x00,
        0x00, 0x08, 0x38, 0x60, 0x00, 0x01, 0x80, 0x01, 0x00, 0x24, 0x83, 0xe1, 0x00, 0x1c, 0x38,
        0x21, 0x00, 0x20, 0x7c, 0x08, 0x03, 0xa6, 0x4e, 0x80, 0x00, 0x20,
    ];
    assert!(object
        .windows(expected.len())
        .any(|bytes| bytes == expected));
}
