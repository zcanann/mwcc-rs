use crate::{compile, SourceLanguage};

#[test]
fn emits_the_legacy_inlined_callback_open_transaction() {
    let source = br#"
        typedef int bool;
        typedef struct Info {
            char prefix[52];
            unsigned int length;
            char suffix[4];
        } Info;
        typedef struct File {
            int unused;
            void* data;
            int pad[2];
            int size;
            int position;
            int kind;
            Info info;
        } File;
        typedef struct ObjectType {
            char* name;
            int size;
            void* argument;
            int (*event)(void*, int, void*);
        } ObjectType;
        typedef int (*OpenCallback)(char*, Info*);

        static OpenCallback open_callback;
        ObjectType file_type;

        extern int make_object(void**, void*, ObjectType*);
        extern int free_object(void**);
        extern int fallback_open(char*, Info*);

        static inline bool get_file(File** output, char* name) {
            if (open_callback != 0) {
                return open_callback(name, &(*output)->info);
            } else {
                return fallback_open(name, &(*output)->info);
            }
        }

        int open_file(File** output, int kind, char* name) {
            if (!make_object((void**)output, 0, &file_type)) {
                return 0;
            }
            if (get_file(output, name)) {
                (*output)->kind = kind;
                (*output)->size = (*output)->info.length;
                (*output)->data = &(*output)->info;
                return 1;
            }
            free_object((void**)output);
            return 0;
        }
    "#;
    let mut flags = mwcc_versions::Flags::default();
    flags.debug_info = false;
    flags.cpp_exceptions = false;
    flags.emit_mwcats = false;
    let object = compile(
        source,
        "inlined-callback-open.c",
        mwcc_versions::CompilerConfig {
            build: mwcc_versions::GC_1_1,
            flags,
        },
        Some(SourceLanguage::C),
        None,
        false,
    )
    .expect("the inlined callback open transaction should compile");

    let expected = [
        0x7c, 0x08, 0x02, 0xa6, 0x3c, 0xc0, 0x00, 0x00, 0x90, 0x01, 0x00, 0x04, 0x38, 0x06, 0x00,
        0x00, 0x94, 0x21, 0xff, 0xd8, 0x93, 0xe1, 0x00, 0x24, 0x3b, 0xe5, 0x00, 0x00, 0x7c, 0x05,
        0x03, 0x78, 0x93, 0xc1, 0x00, 0x20, 0x3b, 0xc4, 0x00, 0x00, 0x38, 0x80, 0x00, 0x00, 0x93,
        0xa1, 0x00, 0x1c, 0x3b, 0xa3, 0x00, 0x00, 0x48, 0x00, 0x00, 0x01, 0x2c, 0x03, 0x00, 0x00,
        0x40, 0x82, 0x00, 0x0c, 0x38, 0x60, 0x00, 0x00, 0x48, 0x00, 0x00, 0x74, 0x81, 0x80, 0x00,
        0x00, 0x28, 0x0c, 0x00, 0x00, 0x41, 0x82, 0x00, 0x1c, 0x80, 0x9d, 0x00, 0x00, 0x7d, 0x88,
        0x03, 0xa6, 0x38, 0x7f, 0x00, 0x00, 0x38, 0x84, 0x00, 0x1c, 0x4e, 0x80, 0x00, 0x21, 0x48,
        0x00, 0x00, 0x14, 0x80, 0x9d, 0x00, 0x00, 0x38, 0x7f, 0x00, 0x00, 0x38, 0x84, 0x00, 0x1c,
        0x48, 0x00, 0x00, 0x01, 0x2c, 0x03, 0x00, 0x00, 0x41, 0x82, 0x00, 0x2c, 0x80, 0x9d, 0x00,
        0x00, 0x38, 0x60, 0x00, 0x01, 0x93, 0xc4, 0x00, 0x18, 0x80, 0x9d, 0x00, 0x00, 0x80, 0x04,
        0x00, 0x50, 0x90, 0x04, 0x00, 0x10, 0x80, 0x9d, 0x00, 0x00, 0x38, 0x04, 0x00, 0x1c, 0x90,
        0x04, 0x00, 0x04, 0x48, 0x00, 0x00, 0x10, 0x7f, 0xa3, 0xeb, 0x78, 0x48, 0x00, 0x00, 0x01,
        0x38, 0x60, 0x00, 0x00, 0x80, 0x01, 0x00, 0x2c, 0x83, 0xe1, 0x00, 0x24, 0x83, 0xc1, 0x00,
        0x20, 0x7c, 0x08, 0x03, 0xa6, 0x83, 0xa1, 0x00, 0x1c, 0x38, 0x21, 0x00, 0x28, 0x4e, 0x80,
        0x00, 0x20,
    ];
    assert!(object
        .windows(expected.len())
        .any(|bytes| bytes == expected));
}
