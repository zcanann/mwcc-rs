use crate::{compile, SourceLanguage};

#[test]
fn emits_the_revolution_global_queue_removal() {
    let source = br#"
        typedef unsigned int u32;

        typedef struct Task {
            u32 state;
            u32 priority;
            u32 flags;
            u32 reserved[11];
            struct Task* next;
            struct Task* prev;
        } Task;

        Task* current_task;
        Task* first_task;
        Task* last_task;

        void remove_task(Task* task) {
            task->flags = 0;
            task->state = 3;

            if (first_task == task) {
                if (task->next != 0) {
                    first_task = task->next;
                    task->next->prev = 0;
                    return;
                }
                first_task = last_task = current_task = 0;
                return;
            }

            if (last_task == task) {
                last_task = task->prev;
                task->prev->next = 0;
                current_task = first_task;
                return;
            }

            current_task = task->next;
            task->prev->next = task->next;
            task->next->prev = task->prev;
        }
    "#;
    let mut flags = mwcc_versions::Flags::default();
    flags.debug_info = false;
    flags.cpp_exceptions = false;
    flags.emit_mwcats = false;
    flags.optimization = mwcc_versions::Optimization::O4;
    flags.ipa_file = true;
    let object = compile(
        source,
        "global-doubly-linked-remove.c",
        mwcc_versions::CompilerConfig {
            build: mwcc_versions::GC_3_0A3,
            flags,
        },
        Some(SourceLanguage::C),
        None,
        false,
    )
    .expect("the Revolution global queue removal should compile");

    let expected = [
        0x38, 0x80, 0x00, 0x00, 0x38, 0x00, 0x00, 0x03, 0x90, 0x83, 0x00, 0x08, 0x90, 0x03, 0x00,
        0x00, 0x80, 0x00, 0x00, 0x00, 0x7c, 0x00, 0x18, 0x40, 0x40, 0x82, 0x00, 0x30, 0x80, 0x03,
        0x00, 0x38, 0x2c, 0x00, 0x00, 0x00, 0x41, 0x82, 0x00, 0x14, 0x90, 0x00, 0x00, 0x00, 0x80,
        0x63, 0x00, 0x38, 0x90, 0x83, 0x00, 0x3c, 0x4e, 0x80, 0x00, 0x20, 0x90, 0x80, 0x00, 0x00,
        0x90, 0x80, 0x00, 0x00, 0x90, 0x80, 0x00, 0x00, 0x4e, 0x80, 0x00, 0x20, 0x80, 0x00, 0x00,
        0x00, 0x7c, 0x00, 0x18, 0x40, 0x40, 0x82, 0x00, 0x20, 0x80, 0x03, 0x00, 0x3c, 0x90, 0x00,
        0x00, 0x00, 0x80, 0x63, 0x00, 0x3c, 0x90, 0x83, 0x00, 0x38, 0x80, 0x00, 0x00, 0x00, 0x90,
        0x00, 0x00, 0x00, 0x4e, 0x80, 0x00, 0x20, 0x80, 0x03, 0x00, 0x38, 0x90, 0x00, 0x00, 0x00,
        0x80, 0x03, 0x00, 0x38, 0x80, 0x83, 0x00, 0x3c, 0x90, 0x04, 0x00, 0x38, 0x80, 0x03, 0x00,
        0x3c, 0x80, 0x63, 0x00, 0x38, 0x90, 0x03, 0x00, 0x3c, 0x4e, 0x80, 0x00, 0x20,
    ];
    assert!(object
        .windows(expected.len())
        .any(|bytes| bytes == expected));
}
