use crate::{compile, SourceLanguage};

#[test]
fn lowers_the_critical_region_raise_transaction_like_mwcc() {
    let source = br#"
        typedef void (*signal_handler)(int);
        extern void begin_region(int);
        extern void end_region(int);
        extern void exit(int);
        signal_handler handlers[6];

        int raise(int sig) {
            signal_handler handler;
            if (sig < 1 || sig > 6) {
                return -1;
            }
            begin_region(4);
            handler = handlers[sig - 1];
            if (handler != (signal_handler)1) {
                handlers[sig - 1] = (signal_handler)0;
            }
            end_region(4);
            if (handler == (signal_handler)1 ||
                (handler == (signal_handler)0 && sig == 1)) {
                return 0;
            }
            if (handler == (signal_handler)0) {
                exit(0);
            }
            handler(sig);
            return 0;
        }
    "#;
    let mut flags = mwcc_versions::Flags::default();
    flags.debug_info = false;
    flags.cpp_exceptions = false;
    flags.emit_mwcats = false;
    let config = mwcc_versions::CompilerConfig {
        build: mwcc_versions::GC_1_3_2,
        flags,
    };
    let object = compile(
        source,
        "signal.c",
        config,
        Some(SourceLanguage::C),
        None,
        false,
    )
    .expect("the critical-region raise transaction should compile");

    // Exact GC/1.3.2 text measured from MSL's signal.c. The transaction keeps
    // `sig` and the handler in r30/r31, folds the indexed load into `lwzu`,
    // clears through that updated address, and shares the cold return blocks.
    let expected = [
        0x94, 0x21, 0xff, 0xf0, 0x7c, 0x08, 0x02, 0xa6, 0x90, 0x01, 0x00, 0x14,
        0x93, 0xe1, 0x00, 0x0c, 0x93, 0xc1, 0x00, 0x08, 0x7c, 0x7e, 0x1b, 0x78,
        0x2c, 0x1e, 0x00, 0x01, 0x41, 0x80, 0x00, 0x0c, 0x2c, 0x1e, 0x00, 0x06,
        0x40, 0x81, 0x00, 0x0c, 0x38, 0x60, 0xff, 0xff, 0x48, 0x00, 0x00, 0x7c,
        0x38, 0x60, 0x00, 0x04, 0x48, 0x00, 0x00, 0x01, 0x3c, 0x60, 0x00, 0x00,
        0x57, 0xc0, 0x10, 0x3a, 0x38, 0x63, 0x00, 0x00, 0x7c, 0x63, 0x02, 0x14,
        0x87, 0xe3, 0xff, 0xfc, 0x28, 0x1f, 0x00, 0x01, 0x41, 0x82, 0x00, 0x0c,
        0x38, 0x00, 0x00, 0x00, 0x90, 0x03, 0x00, 0x00, 0x38, 0x60, 0x00, 0x04,
        0x48, 0x00, 0x00, 0x01, 0x28, 0x1f, 0x00, 0x01, 0x41, 0x82, 0x00, 0x14,
        0x28, 0x1f, 0x00, 0x00, 0x40, 0x82, 0x00, 0x14, 0x2c, 0x1e, 0x00, 0x01,
        0x40, 0x82, 0x00, 0x0c, 0x38, 0x60, 0x00, 0x00, 0x48, 0x00, 0x00, 0x28,
        0x28, 0x1f, 0x00, 0x00, 0x40, 0x82, 0x00, 0x0c, 0x38, 0x60, 0x00, 0x00,
        0x48, 0x00, 0x00, 0x01, 0x7f, 0xec, 0xfb, 0x78, 0x7f, 0xc3, 0xf3, 0x78,
        0x7d, 0x89, 0x03, 0xa6, 0x4e, 0x80, 0x04, 0x21, 0x38, 0x60, 0x00, 0x00,
        0x80, 0x01, 0x00, 0x14, 0x83, 0xe1, 0x00, 0x0c, 0x83, 0xc1, 0x00, 0x08,
        0x7c, 0x08, 0x03, 0xa6, 0x38, 0x21, 0x00, 0x10, 0x4e, 0x80, 0x00, 0x20,
    ];
    assert!(object.windows(expected.len()).any(|bytes| bytes == expected));
}
