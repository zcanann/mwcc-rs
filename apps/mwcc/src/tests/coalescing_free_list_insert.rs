use crate::{compile, SourceLanguage};

#[test]
fn emits_the_sorted_free_list_coalescing_transaction() {
    let source = br#"
        typedef unsigned char u8;
        typedef struct Cell {
            struct Cell* prev;
            struct Cell* next;
            long size;
        } Cell;

        Cell* insert(Cell* list, Cell* cell) {
            Cell* prev;
            Cell* next;

            for (next = list, prev = 0; next != 0; prev = next, next = next->next) {
                if (cell <= next) {
                    break;
                }
            }
            cell->next = next;
            cell->prev = prev;
            if (next) {
                next->prev = cell;
                if ((u8*)cell + cell->size == (u8*)next) {
                    cell->size += next->size;
                    next = next->next;
                    cell->next = next;
                    if (next) {
                        next->prev = cell;
                    }
                }
            }
            if (prev) {
                prev->next = cell;
                if ((u8*)prev + prev->size == (u8*)cell) {
                    prev->size += cell->size;
                    prev->next = next;
                    if (next) {
                        next->prev = prev;
                    }
                }
                return list;
            }
            return cell;
        }
    "#;
    let mut flags = mwcc_versions::Flags::default();
    flags.debug_info = false;
    flags.cpp_exceptions = false;
    flags.emit_mwcats = false;
    let object = compile(
        source,
        "coalescing-free-list-insert.c",
        mwcc_versions::CompilerConfig {
            build: mwcc_versions::GC_1_2_5N,
            flags,
        },
        Some(SourceLanguage::C),
        None,
        false,
    )
    .expect("the coalescing free-list insertion should compile");

    let expected = [
        0x38, 0xe3, 0x00, 0x00, 0x38, 0xc0, 0x00, 0x00, 0x48, 0x00, 0x00, 0x14, 0x7c, 0x04,
        0x38, 0x40, 0x40, 0x81, 0x00, 0x14, 0x7c, 0xe6, 0x3b, 0x78, 0x80, 0xe7, 0x00, 0x04,
        0x28, 0x07, 0x00, 0x00, 0x40, 0x82, 0xff, 0xec, 0x90, 0xe4, 0x00, 0x04, 0x28, 0x07,
        0x00, 0x00, 0x90, 0xc4, 0x00, 0x00, 0x41, 0x82, 0x00, 0x38, 0x90, 0x87, 0x00, 0x00,
        0x80, 0xa4, 0x00, 0x08, 0x7c, 0x04, 0x2a, 0x14, 0x7c, 0x00, 0x38, 0x40, 0x40, 0x82,
        0x00, 0x24, 0x80, 0x07, 0x00, 0x08, 0x7c, 0x05, 0x02, 0x14, 0x90, 0x04, 0x00, 0x08,
        0x80, 0xe7, 0x00, 0x04, 0x28, 0x07, 0x00, 0x00, 0x90, 0xe4, 0x00, 0x04, 0x41, 0x82,
        0x00, 0x08, 0x90, 0x87, 0x00, 0x00, 0x28, 0x06, 0x00, 0x00, 0x41, 0x82, 0x00, 0x38,
        0x90, 0x86, 0x00, 0x04, 0x80, 0xa6, 0x00, 0x08, 0x7c, 0x06, 0x2a, 0x14, 0x7c, 0x00,
        0x20, 0x40, 0x4c, 0x82, 0x00, 0x20, 0x80, 0x04, 0x00, 0x08, 0x28, 0x07, 0x00, 0x00,
        0x7c, 0x05, 0x02, 0x14, 0x90, 0x06, 0x00, 0x08, 0x90, 0xe6, 0x00, 0x04, 0x4d, 0x82,
        0x00, 0x20, 0x90, 0xc7, 0x00, 0x00, 0x4e, 0x80, 0x00, 0x20, 0x7c, 0x83, 0x23, 0x78,
        0x4e, 0x80, 0x00, 0x20,
    ];
    assert!(object.windows(expected.len()).any(|bytes| bytes == expected));
}
